    #[test]
    fn base64_matches_the_rfc_examples() {
        let mut text = String::new();
        base64_encode(&mut text, b"");
        assert_eq!(text, "");
        text.clear();
        base64_encode(&mut text, b"M");
        assert_eq!(text, "TQ==");
        text.clear();
        base64_encode(&mut text, b"Ma");
        assert_eq!(text, "TWE=");
        text.clear();
        base64_encode(&mut text, b"Man");
        assert_eq!(text, "TWFu");
        text.clear();
        base64_encode(&mut text, b"any carnal pleasure.");
        assert_eq!(text, "YW55IGNhcm5hbCBwbGVhc3VyZS4=");
    }

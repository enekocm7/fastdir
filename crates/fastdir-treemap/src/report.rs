//! A self-contained HTML report of a scan.
//!
//! The result is one file with no external assets and no network access:
//! summary totals, an embedded treemap image, the largest files and a
//! collapsible folder tree. It opens in any browser, so a scan can be shared
//! with someone who does not have FastDir installed.
//!
//! The treemap comes from [`crate::render`], so the picture uses the same
//! squarified layout and cushion shading as the app. That is also why this
//! module lives here rather than in `fastdir-core`: it needs the renderer,
//! and the dependency direction is `treemap -> core`.

use crate::treemap::{Palette, RenderOptions, bright_color, ext_color_with, render};
use fastdir_core::format;
use fastdir_core::model::{Node, NodeKind, Tree};
use std::collections::HashMap;
use std::io::{self, Cursor, Write};
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

/// What a report includes and how big it may get.
#[derive(Clone, Debug)]
pub struct ReportOptions {
    /// Deepest level below the exported folder listed in the folder tree
    /// (`None` = no limit). The exported root is level 0.
    pub max_depth: Option<usize>,
    /// List files in the folder tree and include the largest-files table.
    /// The treemap always shows files.
    pub include_files: bool,
    /// Rows in the largest-files table (`0` = omit it).
    pub top_files: usize,
    /// Width and height of the embedded treemap image, in pixels.
    pub treemap_width: u32,
    pub treemap_height: u32,
    /// Hard cap on folder-tree rows, so a huge scan cannot produce a
    /// multi-hundred-megabyte page. Entries are taken largest first.
    pub max_tree_rows: usize,
}

impl Default for ReportOptions {
    fn default() -> Self {
        Self {
            max_depth: None,
            include_files: true,
            top_files: 100,
            treemap_width: 1200,
            treemap_height: 750,
            max_tree_rows: 5_000,
        }
    }
}

/// Write a standalone HTML report of the subtree at `root`. Returns the
/// number of rows written to the folder tree.
pub fn export_html(
    tree: &Tree,
    root: &[u32],
    options: &ReportOptions,
    mut out: impl Write,
) -> io::Result<usize> {
    let (html, rows) = build(tree, root, options)?;
    out.write_all(html.as_bytes())?;
    out.flush()?;
    Ok(rows)
}

/// Like [`export_html`], but creates `dest` first.
pub fn export_html_to_file(
    tree: &Tree,
    root: &[u32],
    options: &ReportOptions,
    dest: &Path,
) -> io::Result<usize> {
    let file = std::fs::File::create(dest)?;
    export_html(tree, root, options, io::BufWriter::new(file))
}

fn invalid(message: impl Into<String>) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidInput, message.into())
}

fn now_unix() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

fn build(tree: &Tree, root: &[u32], options: &ReportOptions) -> io::Result<(String, usize)> {
    let Some(node) = tree.get(root) else {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            "export root not found",
        ));
    };
    let node = *node;
    if !node.is_dir() {
        return Err(invalid("the report root must be a folder"));
    }
    let root_path = tree.fs_path(root).unwrap_or_else(|| tree.root_path.clone());
    let generated = now_unix();
    let mut html = String::with_capacity(96 * 1024);

    html.push_str(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n",
    );
    html.push_str("<title>");
    push_escaped(&mut html, "FastDir report — ");
    push_escaped(&mut html, &root_path.to_string_lossy());
    html.push_str("</title>\n<style>");
    html.push_str(CSS);
    html.push_str("</style>\n</head>\n<body>\n<main>\n<header>\n<h1>Disk usage report</h1>\n<p class=\"sub path\">");
    push_escaped(&mut html, &root_path.to_string_lossy());
    html.push_str("</p>\n<p class=\"sub\">Generated ");
    push_escaped(&mut html, &format::date(generated));
    html.push_str(" by FastDir ");
    html.push_str(env!("CARGO_PKG_VERSION"));
    html.push_str("</p>\n</header>\n");

    write_summary(&mut html, tree, root, &node);
    write_treemap(&mut html, tree, &node, &root_path, options)?;
    if options.include_files {
        write_largest_files(&mut html, tree, root, &node, options);
    }
    let (rows, _truncated) = write_folder_tree(&mut html, tree, &node, options);

    html.push_str("<footer>Generated by FastDir ");
    html.push_str(env!("CARGO_PKG_VERSION"));
    html.push_str(
        ". This file is self-contained: no network access is needed to view it.</footer>\n",
    );
    html.push_str("</main>\n</body>\n</html>\n");
    Ok((html, rows))
}

fn write_summary(html: &mut String, tree: &Tree, root: &[u32], node: &Node) {
    html.push_str("<section>\n<h2>Summary</h2>\n<div class=\"cards\">\n");
    let mut cards: Vec<(&str, String, String)> = vec![
        ("Total size", format::bytes(node.size), String::new()),
        ("Size on disk", format::bytes(node.disk_size), String::new()),
        ("Files", format::count(node.files as u64), String::new()),
        ("Folders", format::count(node.dirs as u64), String::new()),
        ("Items", format::count(node.items()), String::new()),
    ];
    // Volume-wide figures only make sense for a whole-drive scan.
    if root.is_empty() && tree.is_drive_scan() {
        if let Some(free) = tree.free_bytes() {
            cards.push(("Free space", format::bytes(free), String::new()));
        }
        let unknown = tree.unattributed_bytes();
        if unknown > 0 {
            cards.push(("Unknown", format::bytes(unknown), String::new()));
        }
        cards.push((
            "Used",
            format::bytes(tree.used_bytes()),
            "Scanned files plus free space and unknown.".to_string(),
        ));
    }
    for (label, value, sub) in cards {
        html.push_str("<div class=\"card\"><div class=\"k\">");
        push_escaped(html, label);
        html.push_str("</div><div class=\"v\">");
        push_escaped(html, &value);
        html.push_str("</div>");
        if !sub.is_empty() {
            html.push_str("<div class=\"s\">");
            push_escaped(html, &sub);
            html.push_str("</div>");
        }
        html.push_str("</div>\n");
    }
    html.push_str("</div>\n</section>\n");
}

fn write_treemap(
    html: &mut String,
    tree: &Tree,
    node: &Node,
    root_path: &Path,
    options: &ReportOptions,
) -> io::Result<()> {
    let w = options.treemap_width.clamp(64, 4096);
    let h = options.treemap_height.clamp(64, 4096);
    let png = treemap_png(tree, node, w, h)?;
    html.push_str("<section>\n<h2>Treemap</h2>\n<div class=\"treemap\">\n<img width=\"");
    html.push_str(&w.to_string());
    html.push_str("\" height=\"");
    html.push_str(&h.to_string());
    html.push_str("\" alt=\"Treemap of ");
    push_escaped(html, &root_path.to_string_lossy());
    html.push_str("\" src=\"data:image/png;base64,");
    base64_encode(html, &png);
    html.push_str("\">\n</div>\n");
    write_legend(html, tree, node, options.include_files);
    html.push_str("</section>\n");
    Ok(())
}

/// Render the treemap with the app's own CPU renderer and encode it as PNG,
/// so the report is a single file and looks like FastDir.
fn treemap_png(tree: &Tree, node: &Node, w: u32, h: u32) -> io::Result<Vec<u8>> {
    let opts = RenderOptions {
        min_cell: 1.0,
        ..RenderOptions::default()
    };
    let bgra = render(tree, node, w, h, [255, 255, 255], &opts);
    let mut rgb = Vec::with_capacity(w as usize * h as usize * 3);
    for &[b, g, r, _] in bgra.as_chunks::<4>().0 {
        rgb.extend_from_slice(&[r, g, b]);
    }
    let image = image::RgbImage::from_raw(w, h, rgb)
        .ok_or_else(|| invalid("treemap buffer has the wrong size"))?;
    let mut png = Vec::new();
    image
        .write_to(&mut Cursor::new(&mut png), image::ImageFormat::Png)
        .map_err(|e| invalid(format!("could not encode the treemap image: {e}")))?;
    Ok(png)
}

/// Extension colours as the treemap uses them, largest first.
fn write_legend(html: &mut String, tree: &Tree, node: &Node, include_files: bool) {
    if !include_files {
        return;
    }
    let totals = extension_totals(tree, node);
    if totals.is_empty() {
        return;
    }
    html.push_str("<div class=\"legend\">");
    for (ext, bytes) in totals.iter().take(12) {
        let color = bright_color(ext_color_with(Palette::Default, *ext));
        html.push_str("<span><i class=\"sw\" style=\"background:");
        html.push_str(&hex(color));
        html.push_str("\"></i>");
        match tree.exts.get(*ext as usize) {
            Some(stat) => push_escaped(html, &stat.name),
            None => push_escaped(html, "no extension"),
        }
        html.push_str(" <b>");
        push_escaped(html, &format::bytes(*bytes));
        html.push_str("</b></span>");
    }
    let hidden = totals.len().saturating_sub(12);
    if hidden > 0 {
        html.push_str("<span>and ");
        html.push_str(&format::count(hidden as u64));
        html.push_str(" more extensions</span>");
    }
    html.push_str(
        "</div>\n<p class=\"note\">Colours follow the treemap's extension palette. \
                   Free space and unknown bytes are not drawn.</p>\n",
    );
}

/// Bytes per extension below `node`, largest first. Hard-link duplicates add
/// no bytes, so they are left out.
fn extension_totals(tree: &Tree, node: &Node) -> Vec<(u16, u64)> {
    let mut totals: HashMap<u16, u64> = HashMap::new();
    let mut stack = vec![node];
    while let Some(dir) = stack.pop() {
        for child in tree.children(dir) {
            match child.kind() {
                NodeKind::Dir => stack.push(child),
                NodeKind::File if !child.hard_link() => {
                    *totals.entry(child.ext).or_insert(0) += child.size;
                }
                _ => {}
            }
        }
    }
    let mut out: Vec<(u16, u64)> = totals.into_iter().filter(|&(_, b)| b > 0).collect();
    out.sort_unstable_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
    out
}

/// Write the largest-files table.
fn write_largest_files(
    html: &mut String,
    tree: &Tree,
    root: &[u32],
    node: &Node,
    options: &ReportOptions,
) {
    if options.top_files == 0 {
        return;
    }
    let files = tree.top_files_in(root, options.top_files);
    html.push_str("<section>\n<h2>Largest files</h2>\n");
    if files.is_empty() {
        html.push_str("<p class=\"note\">This folder has no files.</p>\n</section>\n");
        return;
    }
    html.push_str(
        "<table>\n<thead><tr><th>File</th><th class=\"num\">Size</th>\
         <th class=\"num\">On disk</th><th class=\"num\">Share</th>\
         <th>Modified</th></tr></thead>\n<tbody>\n",
    );
    for file in &files {
        html.push_str("<tr><td><span class=\"path\">");
        push_escaped(html, &file.name);
        html.push_str("</span>");
        if let Some(parent) = tree
            .fs_path(&file.path)
            .and_then(|p| p.parent().map(Path::to_path_buf))
        {
            html.push_str("<div class=\"where path\">");
            push_escaped(html, &parent.to_string_lossy());
            html.push_str("</div>");
        }
        html.push_str("</td><td class=\"num\">");
        push_escaped(html, &format::bytes(file.size));
        html.push_str("</td><td class=\"num\">");
        push_escaped(html, &format::bytes(file.disk_size));
        html.push_str("</td><td class=\"num\">");
        push_escaped(html, &format::percent(file.size, node.size));
        html.push_str("</td><td>");
        if file.modified > 0 {
            push_escaped(html, &format::date(file.modified));
        } else {
            html.push('—');
        }
        html.push_str("</td></tr>\n");
    }
    html.push_str("</tbody>\n</table>\n</section>\n");
}

/// Write the collapsible folder tree. Returns the number of rows and whether
/// the row budget was reached.
fn write_folder_tree(
    html: &mut String,
    tree: &Tree,
    node: &Node,
    options: &ReportOptions,
) -> (usize, bool) {
    html.push_str("<section>\n<h2>Folder tree</h2>\n<div class=\"tree\">\n");
    let mut rows = 0usize;
    let mut truncated = false;
    write_tree_dir(
        html,
        tree,
        node,
        0,
        node.size,
        options,
        &mut rows,
        &mut truncated,
    );
    html.push_str("</div>\n");
    if truncated {
        html.push_str("<p class=\"note\">Only the first ");
        html.push_str(&format::count(options.max_tree_rows as u64));
        html.push_str(" entries (largest first) are listed.</p>\n");
    }
    if let Some(max) = options.max_depth {
        html.push_str("<p class=\"note\">The tree is limited to ");
        html.push_str(&format::count(max as u64));
        html.push_str(" level(s) below the root.</p>\n");
    }
    if !options.include_files {
        html.push_str("<p class=\"note\">Files are not listed.</p>\n");
    }
    html.push_str("</section>\n");
    (rows, truncated)
}

#[allow(clippy::too_many_arguments)]
fn write_tree_dir(
    html: &mut String,
    tree: &Tree,
    node: &Node,
    depth: usize,
    root_size: u64,
    options: &ReportOptions,
    rows: &mut usize,
    truncated: &mut bool,
) {
    html.push_str(if depth == 0 {
        "<details open><summary>"
    } else {
        "<details><summary>"
    });
    html.push_str("<span class=\"nm\">");
    push_escaped(html, tree.name(node));
    html.push_str("</span><span class=\"sz\">");
    push_escaped(html, &format::bytes(node.size));
    html.push_str("</span><span class=\"pct\">");
    push_escaped(html, &format::percent(node.size, root_size));
    html.push_str("</span></summary>\n");
    *rows += 1;

    let children = tree.children(node);
    for child in children {
        if child.is_special() {
            continue;
        }
        let child_depth = depth + 1;
        if options.max_depth.is_some_and(|max| child_depth > max) {
            continue;
        }
        if *rows >= options.max_tree_rows {
            *truncated = true;
            break;
        }
        match child.kind() {
            NodeKind::Dir => {
                write_tree_dir(
                    html,
                    tree,
                    child,
                    child_depth,
                    root_size,
                    options,
                    rows,
                    truncated,
                );
            }
            NodeKind::File if options.include_files => {
                html.push_str("<div class=\"row\"><span class=\"nm\">");
                push_escaped(html, tree.name(child));
                html.push_str("</span><span class=\"sz\">");
                push_escaped(html, &format::bytes(child.size));
                html.push_str("</span><span class=\"pct\">");
                push_escaped(html, &format::percent(child.size, root_size));
                html.push_str("</span></div>\n");
                *rows += 1;
            }
            _ => {}
        }
    }
    html.push_str("</details>\n");
}

/// Escape text for HTML element content and quoted attributes.
fn push_escaped(out: &mut String, text: &str) {
    for ch in text.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            other => out.push(other),
        }
    }
}

fn hex(color: [f64; 3]) -> String {
    let channel = |value: f64| value.round().clamp(0.0, 255.0) as u8;
    format!(
        "#{:02x}{:02x}{:02x}",
        channel(color[0]),
        channel(color[1]),
        channel(color[2])
    )
}

/// Append `data` to `out` as standard base64, without a line break.
fn base64_encode(out: &mut String, data: &[u8]) {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    out.reserve(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b0 = chunk[0];
        let b1 = chunk.get(1).copied().unwrap_or(0);
        let b2 = chunk.get(2).copied().unwrap_or(0);
        out.push(ALPHABET[(b0 >> 2) as usize] as char);
        out.push(ALPHABET[(((b0 & 0x03) << 4) | (b1 >> 4)) as usize] as char);
        out.push(if chunk.len() > 1 {
            ALPHABET[(((b1 & 0x0f) << 2) | (b2 >> 6)) as usize] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            ALPHABET[(b2 & 0x3f) as usize] as char
        } else {
            '='
        });
    }
}

